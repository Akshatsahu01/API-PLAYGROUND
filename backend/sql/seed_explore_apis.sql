CREATE TABLE IF NOT EXISTS playground_products (
  id INTEGER PRIMARY KEY,
  title TEXT NOT NULL,
  category TEXT NOT NULL,
  price NUMERIC(10, 2) NOT NULL,
  in_stock BOOLEAN NOT NULL
);

CREATE TABLE IF NOT EXISTS playground_books (
  id INTEGER PRIMARY KEY,
  title TEXT NOT NULL,
  author TEXT NOT NULL,
  genre TEXT NOT NULL,
  published_year INTEGER NOT NULL
);

CREATE TABLE IF NOT EXISTS playground_posts (
  id INTEGER PRIMARY KEY,
  user_id INTEGER NOT NULL,
  title TEXT NOT NULL,
  body TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS fake_apis (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  short_desc TEXT NOT NULL,
  description TEXT NOT NULL,
  base_url TEXT NOT NULL,
  category TEXT NOT NULL,
  sample_response JSONB NOT NULL,
  usage_snippet TEXT NOT NULL,
  tags TEXT[] NOT NULL,
  docs_url TEXT
);

